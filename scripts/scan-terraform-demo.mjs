import fs from 'node:fs/promises';
import path from 'node:path';

const repoRoot = process.cwd();
const target = path.join(repoRoot, 'examples/terraform/main.tf');

function finding(severity, title, details, recommendation) {
  return { severity, title, details, recommendation };
}

async function main() {
  let content = '';
  try {
    content = await fs.readFile(target, 'utf8');
  } catch (error) {
    const report = {
      title: 'Terraform Demo Review',
      summary: `Unable to read demo Terraform fixture: ${error.message}`,
      verdict: 'fail',
      findings: [finding('critical', 'Terraform fixture missing', 'The demo workflow could not read the example Terraform file.', 'Restore examples/terraform/main.tf before rerunning the workflow.')],
      next_steps: ['Restore the missing example Terraform file', 'Rerun the PR workflow'],
      notes: ['Generated by the demo scanner.'],
    };
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
    return;
  }

  const findings = [];

  if (content.includes('0.0.0.0/0')) {
    findings.push(
      finding(
        'high',
        'Public ingress exposure',
        'The example Terraform allows inbound traffic from 0.0.0.0/0, which is broader than a normal demo should allow.',
        'Replace the public CIDR with a narrower office, VPN, or test-network range.',
      ),
    );
  }

  const hasOwnerTag = /owner\s*=\s*"[^"]+"/i.test(content);
  if (!hasOwnerTag) {
    findings.push(
      finding(
        'medium',
        'Missing owner tag',
        'The example Terraform fixture does not declare an owner tag, which makes ownership harder to trace.',
        'Add an owner tag with a team or person responsible for the resource.',
      ),
    );
  }

  const verdict = findings.length > 0 ? 'warn' : 'pass';
  const report = {
    title: 'Terraform Demo Review',
    summary:
      findings.length > 0
        ? `The demo Terraform file has ${findings.length} actionable issue${findings.length === 1 ? '' : 's'}.`
        : 'The demo Terraform fixture passed the simple policy checks.',
    verdict,
    findings,
    next_steps:
      findings.length > 0
        ? ['Tighten the Terraform example', 'Rerun the PR workflow to refresh the comment']
        : ['No follow-up required'],
    notes: ['Generated by the demo scanner.', 'This file intentionally stays lightweight and deterministic.'],
  };

  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exitCode = 1;
});
